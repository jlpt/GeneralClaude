def glyph_rows(ch):
    """8 rows of 8-bit ints (MSB = leftmost pixel) for ASCII char `ch`."""
    rows = _G.get(ch, _G[" "])
    out = []
    for r in rows:
        v = 0
        for i, c in enumerate(r):
            if c == "#":
                v |= 0x80 >> (i + 1)
        out.append(v)
    return out + [0]


def ascii_glyphs():
    """dict code -> 8 rows, for 0x20..0x5F."""
    return {c: glyph_rows(chr(c)) for c in range(0x20, 0x60)}
