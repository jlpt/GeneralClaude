#!/usr/bin/env python3
"""Generate src/core2/tp2_text.h (custom dialog binaries) from scene.py.

Each scene is a list of (box, cmd, text) entries in playback order.
box is "T" (top: Banjo/Kazooie) or "B" (bottom: everyone else).
A trigger entry is ("T"/"B", "TRIG", n) and fires event n mid-dialog.
"""
import importlib.util, sys, pathlib

here = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("scene", here / "scene.py")
scene = importlib.util.module_from_spec(spec); spec.loader.exec_module(scene)

WAIT, END, TRIG = 0x06, 0x04, 0x07

def build(lines):
    boxes = {"B": [], "T": []}
    spoke = {"B": False, "T": False}
    last = None
    for box, cmd, text in lines:
        if cmd == "TRIG":
            boxes[box].append((TRIG, bytes([text])))
            continue
        # A box waits for its turn whenever the other box spoke since its last line
        # (or when the other box opened the conversation).
        if last is not None and last != box:
            boxes[box].append((WAIT, b""))
        elif last is None and box == "B":
            pass
        if last is None and box == "T":
            pass
        assert len(text) <= 200, text
        assert text == text.upper(), text
        boxes[box].append((cmd, text.encode("ascii")))
        spoke[box] = True
        last = box
    first = lines[0][0]
    other = "T" if first == "B" else "B"
    # The box that does not open the conversation must start by waiting.
    if spoke[other] and boxes[other][0][0] != WAIT:
        boxes[other].insert(0, (WAIT, b""))
    for b in boxes.values():
        b.append((END, b""))
    out = bytearray()
    for name in ("B", "T"):
        out.append(len(boxes[name]))
        for cmd, s in boxes[name]:
            s = s + b"\0"
            out.append(cmd); out.append(len(s)); out += s
    return bytes(out)

def carr(name, data):
    rows = [", ".join(f"0x{b:02X}" for b in data[i:i+16]) for i in range(0, len(data), 16)]
    return f"static u8 {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

parts = ["/* Generated by bk-turning-point-2/tools/gen_dialog.py - do not edit. */\n"]
names = []
for i, (sname, lines) in enumerate(scene.SCENES):
    n = f"tp2_dialog_{sname}"
    parts.append(carr(n, build(lines)))
    names.append(n)
parts.append(f"#define TP2_DIALOG_COUNT {len(names)}\n")
parts.append("static u8 *tp2_dialogs[TP2_DIALOG_COUNT] = { " + ", ".join(names) + " };\n")
pathlib.Path(sys.argv[1]).write_text("\n".join(parts))
print("wrote", sys.argv[1])
